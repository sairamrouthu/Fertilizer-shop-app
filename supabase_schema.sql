-- Fertilizer Shop Manager starter schema for Supabase (Postgres)
-- Run this in Supabase SQL Editor. Review the policies before production use.
create extension if not exists pgcrypto;

create table if not exists public.farmers (
 id uuid primary key default gen_random_uuid(),
 owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
 farmer_code bigint generated by default as identity,
 name text not null,
 phone text,
 village text,
 created_at timestamptz not null default now()
);
create table if not exists public.products (
 id uuid primary key default gen_random_uuid(),
 owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
 name text not null,
 category text,
 batch_no text,
 expiry_date date,
 purchase_price numeric(12,2) not null default 0 check (purchase_price>=0),
 selling_price numeric(12,2) not null default 0 check (selling_price>=0),
 quantity numeric(14,3) not null default 0 check (quantity>=0),
 unit text not null default 'bag',
 created_at timestamptz not null default now()
);
create table if not exists public.sales (
 id uuid primary key default gen_random_uuid(),
 owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
 farmer_id uuid not null references public.farmers(id),
 product_id uuid not null references public.products(id),
 bill_no text not null,
 sale_date date not null default current_date,
 product_name_snapshot text not null,
 quantity numeric(14,3) not null check(quantity>0),
 unit_price numeric(12,2) not null check(unit_price>=0),
 total numeric(12,2) not null check(total>=0),
 paid numeric(12,2) not null default 0 check(paid>=0 and paid<=total),
 payment_mode text,
 created_at timestamptz not null default now()
);
create table if not exists public.payments (
 id uuid primary key default gen_random_uuid(),
 owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
 farmer_id uuid not null references public.farmers(id),
 amount numeric(12,2) not null check(amount>0),
 mode text,
 payment_date date not null default current_date,
 note text,
 created_at timestamptz not null default now()
);
alter table public.farmers enable row level security;
alter table public.products enable row level security;
alter table public.sales enable row level security;
alter table public.payments enable row level security;
create policy "owner farmers only" on public.farmers for all using (owner_id=auth.uid()) with check (owner_id=auth.uid());
create policy "owner products only" on public.products for all using (owner_id=auth.uid()) with check (owner_id=auth.uid());
create policy "owner sales only" on public.sales for all using (owner_id=auth.uid()) with check (owner_id=auth.uid());
create policy "owner payments only" on public.payments for all using (owner_id=auth.uid()) with check (owner_id=auth.uid());

-- Atomic sale RPC: validates owner, stock and paid amount, then reduces stock + records bill.
create or replace function public.create_sale(
 p_farmer_id uuid, p_product_id uuid, p_quantity numeric,
 p_unit_price numeric, p_paid numeric, p_payment_mode text default 'Cash'
) returns jsonb language plpgsql security invoker set search_path=public as $$
declare pr public.products%rowtype; fr public.farmers%rowtype; v_total numeric(12,2); v_bill text;
begin
 if p_quantity<=0 or p_unit_price<0 or p_paid<0 then raise exception 'Invalid quantity or amount'; end if;
 select * into fr from public.farmers where id=p_farmer_id and owner_id=auth.uid();
 if not found then raise exception 'Farmer not found'; end if;
 select * into pr from public.products where id=p_product_id and owner_id=auth.uid() for update;
 if not found then raise exception 'Product not found'; end if;
 if pr.quantity<p_quantity then raise exception 'Insufficient stock'; end if;
 v_total:=round(p_quantity*p_unit_price,2);
 if p_paid>v_total then raise exception 'Payment cannot exceed bill total'; end if;
 v_bill:='B-'||to_char(clock_timestamp(),'YYMMDDHH24MISS')||'-'||substr(gen_random_uuid()::text,1,4);
 update public.products set quantity=quantity-p_quantity where id=p_product_id and owner_id=auth.uid();
 insert into public.sales(owner_id,farmer_id,product_id,bill_no,sale_date,product_name_snapshot,quantity,unit_price,total,paid,payment_mode)
 values(auth.uid(),p_farmer_id,p_product_id,v_bill,current_date,pr.name,p_quantity,p_unit_price,v_total,p_paid,p_payment_mode);
 return jsonb_build_object('bill_no',v_bill,'total',v_total,'paid',p_paid,'due',v_total-p_paid);
end $$;
grant execute on function public.create_sale(uuid,uuid,numeric,numeric,numeric,text) to authenticated;
